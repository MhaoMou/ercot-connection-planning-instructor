#!/usr/bin/env python3
"""Render frozen tutorial transcripts as deterministic LaTeX includes.

This script reads only checked-in JSON transcripts. It never calls a model.
The output directory is a build directory and should not be committed.
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
FENCE_RE = re.compile(r"```([A-Za-z0-9_+.-]*)\n(.*?)```", re.DOTALL)
INLINE_CODE_RE = re.compile(r"`([^`]+)`")


def latex_escape(text: str) -> str:
    """Escape ordinary transcript prose for LaTeX text mode."""
    replacements = {
        "\\": r"\textbackslash{}",
        "%": r"\%",
        "&": r"\&",
        "_": r"\_",
        "#": r"\#",
        "{": r"\{",
        "}": r"\}",
        "$": r"\$",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
    }
    return "".join(replacements.get(character, character) for character in text)


def _markdown_text(text: str) -> str:
    def render_inline(value: str) -> str:
        chunks = []
        cursor = 0
        for match in INLINE_CODE_RE.finditer(value):
            chunks.append(latex_escape(value[cursor : match.start()]))
            chunks.append(r"\path{" + match.group(1) + "}")
            cursor = match.end()
        chunks.append(latex_escape(value[cursor:]))
        return "".join(chunks)

    lines = []
    for line in text.splitlines():
        if line.startswith("### "):
            lines.append(r"\textbf{" + render_inline(line[4:]) + "}\\")
        elif line.startswith("## "):
            lines.append(r"\textbf{" + render_inline(line[3:]) + "}\\")
        elif line.startswith("- ") or line.startswith("* "):
            lines.append(r"\textbullet\ " + render_inline(line[2:]) + r"\\")
        else:
            lines.append(render_inline(line) + r"\par")
    return "\n".join(lines)


def render_response(response: str) -> str:
    """Render prose safely and code fences as listings blocks."""
    chunks = []
    cursor = 0
    for match in FENCE_RE.finditer(response):
        chunks.append(_markdown_text(response[cursor : match.start()]))
        language = match.group(1).lower()
        language = {"py": "Python", "python": "Python", "matlab": "Matlab", "bash": "bash", "sh": "bash", "csv": "CSV", "json": "JSON"}.get(language, "")
        code = match.group(2)
        option = "[language=" + language + "]" if language else ""
        chunks.append(_render_listing(code, option))
        cursor = match.end()
    chunks.append(_markdown_text(response[cursor:]))
    return "\n".join(chunks)


def _render_listing(code: str, option: str) -> str:
    """Render code while keeping a literal listings terminator inert."""
    pieces = code.rstrip().split(r"\end{lstlisting}")
    rendered = []
    for index, piece in enumerate(pieces):
        rendered.append("\\begin{lstlisting}" + option + "\n" + piece + "\n\\end{lstlisting}")
        if index < len(pieces) - 1:
            rendered.append(r"\textbackslash end\{lstlisting\}")
    return "\n".join(rendered) + "\n"


def _load_validator(path: Path, name: str):
    spec = importlib.util.spec_from_file_location(name, path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"cannot load validator: {path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def validate_sources() -> None:
    """Run the checked-in prompt and transcript validators before rendering."""
    registry_validator = _load_validator(
        ROOT / "scripts" / "validate_prompt_registry.py", "tutorial_prompt_registry_validator"
    )
    transcript_validator = _load_validator(
        ROOT / "scripts" / "validate_transcripts.py", "tutorial_transcript_validator"
    )
    errors = []
    if registry_validator.validate_registry() != 0:
        errors.append("prompt registry validation failed")
    if transcript_validator.validate_transcripts() != 0:
        errors.append("transcript validation failed")
    if errors:
        raise RuntimeError("; ".join(errors))


def _validate_transcript_for_build(transcript: dict, label: str) -> None:
    response = transcript.get("response")
    normalized = " ".join(response.casefold().split()) if isinstance(response, str) else ""
    if transcript.get("review_status") != "fact-checked":
        raise ValueError(f"{label}: transcript must be fact-checked")
    if not normalized or normalized in {"todo", "tbd", "pending", "placeholder", "[placeholder]"}:
        raise ValueError(f"{label}: response must not be a placeholder")


def build(output_dir: Path) -> int:
    validate_sources()
    registry = json.loads((ROOT / "prompt_registry.json").read_text(encoding="utf-8"))
    output_dir.mkdir(parents=True, exist_ok=True)
    sections = ["% Generated by build_latex_inputs.py; do not edit.\n"]
    for item in registry["prompts"]:
        transcript = json.loads((ROOT / item["transcript_file"]).read_text(encoding="utf-8"))
        _validate_transcript_for_build(transcript, str(item["id"]))
        title = item["module"]
        label = "transcript:" + item["id"]
        checklist = "\\begin{itemize}[leftmargin=*]\n" + "\n".join(
            r"\item " + latex_escape(str(entry)) for entry in transcript["verification_checklist"]
        ) + "\n\\end{itemize}"
        sections.extend(
            [
                f"\\subsection{{{latex_escape(title)}}}\\label{{{label}}}\n",
                "\\begin{promptbox}\n\\textbf{Frozen prompt.}\\par\n",
                _markdown_text(transcript["prompt"]),
                "\\end{promptbox}\n",
                "\\begin{aibox}\n\\textbf{Reviewed transcript output.}\\par\n",
                render_response(transcript["response"]),
                "\\end{aibox}\n",
                "\\begin{verifybox}\n\\textbf{Verification checklist.}\\par\n",
                checklist,
                "\\end{verifybox}\n",
            ]
        )
    (output_dir / "transcripts.tex").write_text("\n".join(sections), encoding="utf-8")
    print(f"wrote {len(registry['prompts'])} transcript sections to {output_dir / 'transcripts.tex'}")
    return len(registry["prompts"])


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=ROOT / "generated")
    args = parser.parse_args()
    build(args.output_dir)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
