#!/usr/bin/env python3
"""Render frozen tutorial transcripts as deterministic LaTeX includes.

This script reads only checked-in JSON transcripts. It never calls a model.
The output directory is a build directory and should not be committed.
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
FENCE_RE = re.compile(r"```([A-Za-z0-9_+.-]*)\n(.*?)```", re.DOTALL)


def latex_escape(text: str) -> str:
    """Escape ordinary transcript prose for LaTeX text mode."""
    replacements = (
        ("\\", r"\textbackslash{}"),
        ("%", r"\%"),
        ("&", r"\&"),
        ("_", r"\_"),
        ("#", r"\#"),
        ("{", r"\{"),
        ("}", r"\}"),
        ("~", r"\textasciitilde{}"),
        ("^", r"\textasciicircum{}"),
    )
    for old, new in replacements:
        text = text.replace(old, new)
    return text


def _markdown_text(text: str) -> str:
    lines = []
    for line in text.splitlines():
        if line.startswith("### "):
            lines.append(r"\textbf{" + latex_escape(line[4:]) + "}\\")
        elif line.startswith("## "):
            lines.append(r"\textbf{" + latex_escape(line[3:]) + "}\\")
        elif line.startswith("- ") or line.startswith("* "):
            lines.append(r"\textbullet\ " + latex_escape(line[2:]) + r"\\")
        else:
            lines.append(latex_escape(line) + r"\par")
    return "\n".join(lines)


def render_response(response: str) -> str:
    """Render prose safely and code fences as listings blocks."""
    chunks = []
    cursor = 0
    for match in FENCE_RE.finditer(response):
        chunks.append(_markdown_text(response[cursor : match.start()]))
        language = match.group(1).lower()
        language = {"py": "Python", "python": "Python", "matlab": "Matlab", "bash": "bash", "sh": "bash", "csv": "CSV", "json": "JSON"}.get(language, "")
        code = match.group(2).replace("\\end{lstlisting}", "\\end{lstlisting}{}")
        option = "[language=" + language + "]" if language else ""
        chunks.append("\\begin{lstlisting}" + option + "\n" + code.rstrip() + "\n\\end{lstlisting}\n")
        cursor = match.end()
    chunks.append(_markdown_text(response[cursor:]))
    return "\n".join(chunks)


def build(output_dir: Path) -> int:
    registry = json.loads((ROOT / "prompt_registry.json").read_text(encoding="utf-8"))
    output_dir.mkdir(parents=True, exist_ok=True)
    sections = ["% Generated by build_latex_inputs.py; do not edit.\n"]
    for item in registry["prompts"]:
        transcript = json.loads((ROOT / item["transcript_file"]).read_text(encoding="utf-8"))
        title = item["module"]
        label = "transcript:" + item["id"]
        checklist = "\\begin{itemize}[leftmargin=*]\n" + "\n".join(
            r"\item " + latex_escape(str(entry)) for entry in transcript["verification_checklist"]
        ) + "\n\\end{itemize}"
        sections.extend(
            [
                f"\\subsection{{{latex_escape(title)}}}\\label{{{label}}}\n",
                "\\begin{promptbox}\n\\textbf{Frozen prompt.}\\par\n",
                _markdown_text(transcript["prompt"]),
                "\\end{promptbox}\n",
                "\\begin{aibox}\n\\textbf{Reviewed transcript output.}\\par\n",
                render_response(transcript["response"]),
                "\\end{aibox}\n",
                "\\begin{verifybox}\n\\textbf{Verification checklist.}\\par\n",
                checklist,
                "\\end{verifybox}\n",
            ]
        )
    (output_dir / "transcripts.tex").write_text("\n".join(sections), encoding="utf-8")
    print(f"wrote {len(registry['prompts'])} transcript sections to {output_dir / 'transcripts.tex'}")
    return len(registry["prompts"])


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=ROOT / "generated")
    args = parser.parse_args()
    build(args.output_dir)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
